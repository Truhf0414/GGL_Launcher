// 重產 ARCHITECTURE.md 的 IPC 索引。handler 由哪支檔註冊，取自實際跑一次註冊的結果（scripts/lib/ipc-registry.js）。
// 不寫行號：行號隨任何改動漂移，寫了文件就天天過期。
const fs = require("fs");
const path = require("path");
const { ALLOWED_INVOKE, ALLOWED_ON } = require("../lib/ipc-channels");
const {
  collectRegisteredHandlers,
  compareWithAllowlist,
} = require("./lib/ipc-registry");

const ARCH_PATH = path.resolve(__dirname, "..", "ARCHITECTURE.md");
const START = "<!-- IPC_INDEX:START -->";
const END = "<!-- IPC_INDEX:END -->";

function sorted(arr) {
  return [...arr].sort((a, b) => a.localeCompare(b));
}

function renderIndex(handlers) {
  const fileOf = new Map(handlers.map((h) => [h.channel, h.file]));
  const out = [
    "### IPC index (auto-generated by `npm run docs:ipc`)",
    "",
    "- **Channel source**: `lib/ipc-channels.js`（`preload.js` 的 allowlist 也從這裡來）",
    "- **Handler 與 allowlist 是否對上**：`test/ipc-registry.test.cjs` 守",
    "",
    "#### Invoke channels (`window.ggl.invoke`)",
    "",
    ...sorted(ALLOWED_INVOKE).map((c) => `- \`${c}\` (\`${fileOf.get(c)}\`)`),
    "",
    "#### Event channels (`window.ggl.on`)",
    "",
    ...sorted(ALLOWED_ON).map((c) => `- \`${c}\``),
    "",
  ];
  return out.join("\n");
}

function upsertBlock(doc, body) {
  const s = doc.indexOf(START);
  const e = doc.indexOf(END);
  if (s === -1 || e === -1 || e < s) {
    throw new Error(`ARCHITECTURE.md missing markers: ${START} / ${END}`);
  }
  return `${doc.slice(0, s + START.length)}\n\n${body}\n${doc.slice(e)}`;
}

function main() {
  const handlers = collectRegisteredHandlers();
  const { missing, extra, duplicated } = compareWithAllowlist(
    ALLOWED_INVOKE,
    handlers,
  );
  if (missing.length || extra.length || duplicated.length) {
    console.error("IPC handler 與 allowlist 對不上，不產索引：", {
      missing,
      extra,
      duplicated,
    });
    process.exit(1);
  }
  const arch = fs.readFileSync(ARCH_PATH, "utf8");
  fs.writeFileSync(ARCH_PATH, upsertBlock(arch, renderIndex(handlers)), "utf8");
  console.log("Updated ARCHITECTURE.md IPC index.");
}

main();
